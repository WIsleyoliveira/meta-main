suppressMessages(library(ragg))
set.seed(1)
fn <- "out/synth_km.png"
agg_png(fn, width = 1000, height = 700, res = 100)
par(mar = c(5, 5, 2, 2))
tt <- seq(0, 60, by = 0.25)
s1 <- exp(-0.025 * tt); s0 <- exp(-0.045 * tt)
plot(NA, xlim = c(0, 60), ylim = c(0, 1), xaxs = "i", yaxs = "i", xlab = "Months", ylab = "Overall survival", axes = FALSE)
axis(1, at = seq(0, 60, 12)); axis(2, at = seq(0, 1, .2), las = 1); box()
lines(tt, s1, type = "s", col = "#2F5D8A", lwd = 3); lines(tt, s0, type = "s", col = "#B23A48", lwd = 3)
px <- grconvertX(c(0, 60), "user", "device"); py <- grconvertY(c(0, 1), "user", "device")
dev.off()
cat(jsonlite::toJSON(list(x = px, y = py)), "\n", file = "out/synth_cal.json")
print(px); print(py)
