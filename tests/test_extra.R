suppressMessages({library(meta)}); source("R/extra_helpers.R")
ok <- function(c, m) { cat(if (isTRUE(c)) "OK  " else "FAIL", m, "\n"); if (!isTRUE(c)) quit(status = 1) }
set.seed(2); k <- 12
yr <- 2000 + 1:k; te <- -0.2 - 0.02 * (yr - 2000) + rnorm(k, 0, 0.05); se <- runif(k, .08, .2)
m <- metagen(TE = te, seTE = se, studlab = paste("S", 1:k), sm = "HR", method.tau = "REML")
d <- data.frame(study = m$studlab, year = yr, design = rep(c("RCT", "Cohort"), 6), notes = letters[1:12], n = 1:12, stringsAsFactors = FALSE)
cd <- mr_candidates(d, exclude = "study"); print(cd)
ok(all(c("year", "design", "n") %in% cd$col) && !"notes" %in% cd$col && cd$kind[cd$col == "design"] == "group", "covariate candidates are found and typed")
r <- mr_run(m, mr_covariate(d$year, "number"), "number", "year", "REML", TRUE)
ok(r$ok && r$k == k && r$table$p[2] < 0.05 && r$table$estimate[2] < 0, "meta-regression recovers the downward trend")
ok(abs(r$table$estimate[2] - (-0.02)) < 0.015, sprintf("slope near the true -0.02 (%.4f)", r$table$estimate[2]))
ok(!is.null(r$table$ratio) && grepl("ratio per 1-unit", r$text), "ratio measure shows exp(slope)"); cat(r$text, "\n")
g <- mr_run(m, mr_covariate(d$design, "group"), "group", "design"); ok(g$ok && nrow(g$table) == 2, "group covariate works")
bad <- mr_run(m, rep(1, k), "number", "x"); ok(!bad$ok, "a constant covariate is refused")
few <- mr_run(metagen(te[1:2], se[1:2]), c(1, 2), "number", "x"); ok(!few$ok, "fewer than 3 studies is refused")
png(tempfile()); mr_plot(r); mr_plot(g); dev.off()
i <- infl_run(m, "REML", TRUE); ok(i$ok && nrow(i$table) == k && all(is.finite(i$table$I2_without)), "influence table has one row per study")
png(tempfile(), 800, 800); infl_plot(i); baujat_plot(m); radial_plot(m); dev.off(); cat(infl_note(i), "\n")
m2 <- metabin(c(5, 8, 3, 9, 4), c(50, 60, 40, 70, 55), c(9, 12, 8, 14, 6), c(50, 60, 40, 70, 55), sm = "OR"); i2 <- infl_run(m2); ok(i2$ok, "works on a dichotomous model")
cat("EXTRA HELPERS TESTS PASSED\n")
