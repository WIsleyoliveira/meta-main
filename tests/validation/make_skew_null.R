# Builds R/conv_skew_null.R: the null distribution (normal data) of two asymmetry indices, by sample size.
#   Bowley index   B = (Q1 + Q3 - 2 median) / (Q3 - Q1)
#   Range index    R = (min + max - 2 median) / (max - min)
# For each n the absolute index is summarised at several levels, so the app can turn an observed index into an approximate p-value.
set.seed(20261014)
ns <- c(8, 10, 15, 20, 30, 40, 50, 75, 100, 150, 200, 300, 500, 1000, 3000)
lv <- c(0.5, 0.7, 0.8, 0.9, 0.95, 0.975, 0.99)
reps <- 40000
bow <- matrix(NA_real_, length(ns), length(lv)); rng <- bow
for (i in seq_along(ns)) {
  n <- ns[i]; b <- numeric(reps); r <- numeric(reps)
  for (k in seq_len(reps)) {
    x <- rnorm(n); q <- quantile(x, c(.25, .5, .75), names = FALSE, type = 7); mn <- min(x); mx <- max(x)
    b[k] <- (q[1] + q[3] - 2 * q[2]) / (q[3] - q[1]); r[k] <- (mn + mx - 2 * q[2]) / (mx - mn)
  }
  bow[i, ] <- quantile(abs(b), lv); rng[i, ] <- quantile(abs(r), lv)
}
fmt <- function(m) paste0("matrix(c(", paste(formatC(as.vector(m), digits = 5, format = "g"), collapse = ", "), "), nrow = ", nrow(m), ")")
writeLines(c("# Generated by tests/validation/make_skew_null.R. Do not edit by hand.",
  "# Null (normal data) quantiles of |asymmetry index| by sample size: rows = SKEW_NULL_N, columns = SKEW_NULL_LEVELS.",
  sprintf("SKEW_NULL_N <- c(%s)", paste(ns, collapse = ", ")),
  sprintf("SKEW_NULL_LEVELS <- c(%s)", paste(lv, collapse = ", ")),
  sprintf("SKEW_NULL_BOWLEY <- %s", fmt(bow)),
  sprintf("SKEW_NULL_RANGE <- %s", fmt(rng))), "R/conv_skew_null.R")
cat("written\n")
